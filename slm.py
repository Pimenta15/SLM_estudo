from transformers import GPT2Tokenizer, GPT2LMHeadModel
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import Dataset, DataLoader, random_split

if torch.cuda.is_available():
  device = torch.device('cuda')
else:
  device = torch.device('cpu')

device

tokenizer = GPT2Tokenizer.from_pretrained('distilgpt2')
model = GPT2LMHeadModel.from_pretrained('distilgpt2').to(device)
model

""" O tokenizador converte o texto em números, e o modelo GPT-2 será usado para gerar a linguagem."""

BATCH_SIZE = 18

#Preparar Dataset
class LanguageDataset(Dataset):
    """
      Uma extensão do objeto Dataset para:
      - Tornar o ciclo de treinamento mais facil
      - Facilitar o consumo de df's pandas
    """
    def __init__(self, df, tokenizer):
        self.labels = df.columns
        self.data = df.to_dict(orient='records')
        self.tokenizer = tokenizer
        x = self.fittest_max_length(df)  #
        self.max_length = x

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        x = self.data[idx][self.labels[0]]
        y = self.data[idx][self.labels[1]]
        text = f"{x} | {y}"
        tokens = self.tokenizer.encode_plus(text, return_tensors='pt', max_length=128, padding='max_length', truncation=True)
        return tokens

    def fittest_max_length(self, df):  #
        max_length = max(len(max(df[self.labels[0]], key=len)), len(max(df[self.labels[1]], key=len)))
        x = 2
        while x < max_length: x = x * 2
        return x

data_sample = LanguageDataset(df, tokenizer)

"""Separação dos Dados em Treino e Validação"""

train_size = int(0.8 * len(data_sample))
valid_size = len(data_sample) - train_size
train_data, valid_data = random_split(data_sample, [train_size, valid_size])

"""Preparação do Dataloader"""

train_loader = DataLoader(train_data, batch_size=BATCH_SIZE, shuffle=True)
valid_loader = DataLoader(valid_data, batch_size=BATCH_SIZE)

num_epochs = 10

"""Definição dos Hiperparâmetros"""

batch_size = BATCH_SIZE
model_name = 'distilgpt2'
gpu = 0

criterion = nn.CrossEntropyLoss(ignore_index = tokenizer.pad_token_id)
optimizer = optim.Adam(model.parameters(), lr=5e-4)
tokenizer.pad_token = tokenizer.eos_token

# Inicia um dataframe de resultados
results = pd.DataFrame(columns=['epoch', 'transformer', 'batch_size', 'gpu', 'training_loss', 'validation_loss', 'epoch_duration_sec'])

#loop de treinamento
for epoch in range(num_epochs):
    start_time = time.time()  # Iniciar cronometro da epoca
    # Treinamento
    model.train() # Informa ao modelo que estamos em 'modo de aprendizagem'
    epoch_training_loss = 0
    train_iterator = tqdm(train_loader, desc=f"Training Epoch {epoch+1}/{num_epochs} Batch Size: {batch_size}, Transformer: {model_name}")
    for batch in train_iterator:
        optimizer.zero_grad() # Zera os gradientes acumulados
        inputs = batch['input_ids'].squeeze(1).to(device) #Prepara as entradas
        targets = inputs.clone() # O alvo é igual as entradas (para treinamento autoregressivo)
        outputs = model(input_ids=inputs, labels=targets) # Passa os inputs e targets para o modelo
        loss = outputs.loss # Calcula a perda
        loss.backward() # Backward pass (calcula gradientes)
        optimizer.step()  # Atualiza os pesos do modelo
        train_iterator.set_postfix({'Training Loss': loss.item()})
        epoch_training_loss += loss.item() # A perda do lote é adicionada ao total da época
    avg_epoch_training_loss = epoch_training_loss / len(train_iterator)

    # Validação

    model.eval() # O modelo é colocado no modo de avaliação
    epoch_validation_loss = 0
    total_loss = 0
    valid_iterator = tqdm(valid_loader, desc=f"Validation Epoch {epoch+1}/{num_epochs}")
    with torch.no_grad(): # Modelo não precisa ajustar pesos na validação (economizar memória)
        for batch in valid_iterator:
            inputs = batch['input_ids'].squeeze(1).to(device)
            targets = inputs.clone()
            outputs = model(input_ids=inputs, labels=targets)
            loss = outputs.loss
            total_loss += loss
            valid_iterator.set_postfix({'Validation Loss': loss.item()})
            epoch_validation_loss += loss.item()

    avg_epoch_validation_loss = epoch_validation_loss / len(valid_loader)

    end_time = time.time() # Fim do tempo da epoca
    epoch_duration_sec = end_time - start_time  # Calcula a duração da epoca em segundos

    new_row = {'transformer': model_name,
               'batch_size': batch_size,
               'gpu': gpu,
               'epoch': epoch+1,
               'training_loss': avg_epoch_training_loss,
               'validation_loss': avg_epoch_validation_loss,
               'epoch_duration_sec': epoch_duration_sec}

    results.loc[len(results)] = new_row
    print(f"Epoch: {epoch+1}, Validation Loss: {total_loss/len(valid_loader)}")

print(results)

